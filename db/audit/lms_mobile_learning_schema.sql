CREATE VIEW derived.teacher_course_overview AS
 WITH teacher_courses AS (
         SELECT DISTINCT ra.userid AS teacherid,
            ctx.instanceid AS courseid
           FROM ((lms.role_assignments ra
             JOIN lms.role r ON ((r.id = ra.roleid)))
             JOIN lms.context ctx ON ((ctx.id = ra.contextid)))
          WHERE ((ctx.contextlevel = 50) AND (((r.shortname)::text = ANY ((ARRAY['teacher'::character varying, 'editingteacher'::character varying])::text[])) OR ((r.archetype)::text = ANY ((ARRAY['teacher'::character varying, 'editingteacher'::character varying])::text[]))))
        ), student_metrics AS (
         SELECT student_course_progress.courseid,
            count(DISTINCT student_course_progress.userid) AS student_count,
            round(avg(student_course_progress.progress_percentage), 2) AS average_progress
           FROM derived.student_course_progress
          GROUP BY student_course_progress.courseid
        ), risk_metrics AS (
         SELECT student_risk_indicator.courseid,
            count(*) FILTER (WHERE (student_risk_indicator.risk_level = 'HIGH'::text)) AS high_risk_students,
            count(*) FILTER (WHERE (student_risk_indicator.risk_level = 'MEDIUM'::text)) AS medium_risk_students,
            count(*) FILTER (WHERE (student_risk_indicator.risk_level = ANY (ARRAY['MEDIUM'::text, 'HIGH'::text]))) AS students_need_attention
           FROM derived.student_risk_indicator
          GROUP BY student_risk_indicator.courseid
        ), deadline_source AS (
         SELECT assign.course AS courseid,
            assign.duedate AS deadline
           FROM lms.assign
          WHERE (assign.duedate > 0)
        UNION ALL
         SELECT quiz.course AS courseid,
            quiz.timeclose AS deadline
           FROM lms.quiz
          WHERE (quiz.timeclose > 0)
        ), deadline_metrics AS (
         SELECT deadline_source.courseid,
            count(*) FILTER (WHERE ((deadline_source.deadline >= (EXTRACT(epoch FROM CURRENT_TIMESTAMP))::bigint) AND (deadline_source.deadline <= ((EXTRACT(epoch FROM CURRENT_TIMESTAMP))::bigint + 604800)))) AS upcoming_deadlines_7_days
           FROM deadline_source
          GROUP BY deadline_source.courseid
        ), latest_submissions AS (
         SELECT DISTINCT ON (assign_submission.assignment, assign_submission.userid) assign_submission.assignment,
            assign_submission.userid,
            assign_submission.status,
            assign_submission.attemptnumber,
            assign_submission.latest,
            assign_submission.timemodified
           FROM lms.assign_submission
          ORDER BY assign_submission.assignment, assign_submission.userid, assign_submission.latest DESC, assign_submission.attemptnumber DESC, assign_submission.timemodified DESC
        ), grading_metrics AS (
         SELECT a.course AS courseid,
            count(*) FILTER (WHERE (((ls.status)::text = 'submitted'::text) AND ((ag.id IS NULL) OR (ag.grade IS NULL)))) AS needs_grading_count
           FROM ((latest_submissions ls
             JOIN lms.assign a ON ((a.id = ls.assignment)))
             LEFT JOIN lms.assign_grades ag ON (((ag.assignment = ls.assignment) AND (ag.userid = ls.userid) AND (ag.attemptnumber = ls.attemptnumber))))
          GROUP BY a.course
        )
 SELECT c.id AS courseid,
    c.fullname AS course_name,
    c.shortname AS course_shortname,
    COALESCE(sm.student_count, (0)::bigint) AS student_count,
    COALESCE(sm.average_progress, (0)::numeric) AS average_progress,
    COALESCE(rm.high_risk_students, (0)::bigint) AS high_risk_students,
    COALESCE(rm.medium_risk_students, (0)::bigint) AS medium_risk_students,
    COALESCE(rm.students_need_attention, (0)::bigint) AS students_need_attention,
    COALESCE(dm.upcoming_deadlines_7_days, (0)::bigint) AS upcoming_deadlines_7_days,
    COALESCE(gm.needs_grading_count, (0)::bigint) AS needs_grading_count,
    tc.teacherid
   FROM (((((teacher_courses tc
     JOIN lms.course c ON ((c.id = tc.courseid)))
     LEFT JOIN student_metrics sm ON ((sm.courseid = c.id)))
     LEFT JOIN risk_metrics rm ON ((rm.courseid = c.id)))
     LEFT JOIN deadline_metrics dm ON ((dm.courseid = c.id)))
     LEFT JOIN grading_metrics gm ON ((gm.courseid = c.id)));


