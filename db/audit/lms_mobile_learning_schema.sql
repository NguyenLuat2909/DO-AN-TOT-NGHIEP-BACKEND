            e.days_since_last_activity,
            LEAST(100, (((
                CASE
                    WHEN (COALESCE(e.days_since_last_activity, 999) >= 14) THEN 40
                    WHEN (COALESCE(e.days_since_last_activity, 999) >= 7) THEN 25
