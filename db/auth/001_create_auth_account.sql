-- REVIEW AND RUN MANUALLY ONLY. Never changes Moodle/PostgreSQL credentials.
BEGIN;
CREATE TABLE IF NOT EXISTS app.auth_account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid bigint NOT NULL UNIQUE REFERENCES lms."user"(id),
    username varchar(100) NOT NULL UNIQUE,
    password_hash varchar(60) NOT NULL CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT auth_account_username_nonempty CHECK (username = btrim(username) AND username <> '')
);
COMMIT;
